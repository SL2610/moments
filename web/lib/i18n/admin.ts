export type AdminKey = keyof (typeof admin)["he"];

export function useAdminText() {
	const { locale } = useI18n();
	return (key: AdminKey, vars: Record<string, string | number> = {}) =>
		Object.entries(vars).reduce<string>((s, [k, v]) => s.replaceAll(`{${k}}`, String(v)), admin[locale][key]);
}
